/**
 * Расписание ролика по сетке трека «Музыка для промо»: 105 BPM, первая доля
 * на 0.12 с. Смены сцен стоят на сильных долях, поэтому монтаж совпадает с
 * музыкой без подгонки. Время везде считается от доли: b(164) — второй дроп.
 */
export const BPM = 105;
export const BEAT = 60 / BPM;
const OFFSET = 0.12;

/** Время доли n в секундах, дробные доли допустимы */
export const b = (n: number) => OFFSET + n * BEAT;

/** Секции трека (доли): границы найдены анализом спектра и атак */
export const SEC = {
  intro: 0, // фильтрованное вступление
  hats: 16, // входят хэты
  download: 32, // куплет 1 — загрузки
  record: 64, // куплет 2 — запись и VPS
  drop: 96, // первый дроп — ИИ-инструменты
  breakdown: 128, // брейкдаун — воркспейсы
  build: 144, // подъём — палитра, пресеты, логи
  gap: 160, // пауза перед дропом
  drop2: 164, // второй дроп — всё в одном окне
  outro: 196, // финал
  hit: 212, // последний удар
} as const;

/** Длительность ролика: хвост трека после последнего удара */
export const END = 125;
