// Regenerates src/ui/redesign/icons/motion/iconNodes.generated.ts from the lucide-react
// icons imported by iconMap.tsx. Run after upgrading lucide-react: node scripts/gen-icon-nodes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mapFile = path.join(root, "src/ui/redesign/icons/iconMap.tsx");
const outFile = path.join(root, "src/ui/redesign/icons/motion/iconNodes.generated.ts");
const iconsDir = path.join(root, "node_modules/lucide-react/dist/esm/icons");

const source = fs.readFileSync(mapFile, "utf8");
const importBlock = source.match(/import\s*\{([^}]+)\}\s*from\s*"lucide-react";/g)?.find((b) => !b.includes("type "));
if (!importBlock) throw new Error("lucide-react import not found in iconMap.tsx");
const names = importBlock
  .replace(/import\s*\{|\}\s*from\s*"lucide-react";/g, "")
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean);

const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])(\d)/g, "$1-$2").toLowerCase();

async function loadNode(name) {
  const candidates = [kebab(name), kebab(name).replace(/-(\d)/g, "$1")];
  const file = candidates.map((c) => path.join(iconsDir, `${c}.js`)).find((f) => fs.existsSync(f));
  if (!file) throw new Error(`lucide icon file not found for ${name}`);
  const mod = await import(pathToFileURL(file).href);
  if (mod.__iconNode) return mod.__iconNode;
  const reexport = fs.readFileSync(file, "utf8").match(/from '\.\/(.+?)'/);
  if (!reexport) throw new Error(`no __iconNode for ${name}`);
  const target = await import(pathToFileURL(path.join(iconsDir, reexport[1])).href);
  return target.__iconNode;
}

const nodes = {};
for (const name of names) {
  nodes[name] = (await loadNode(name)).map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
}

function mapBlock(constName) {
  const start = source.indexOf(`export const ${constName} = {`);
  if (start < 0) throw new Error(`${constName} not found in iconMap.tsx`);
  const block = source.slice(start, source.indexOf("} as const", start));
  const entries = [...block.matchAll(/^\s+(\w+):\s*([A-Z]\w+),/gm)].map(([, key, comp]) => {
    if (!nodes[comp]) throw new Error(`${constName}.${key} uses ${comp}, which is not imported from lucide-react`);
    return `  ${key}: ${JSON.stringify(nodes[comp])},`;
  });
  return entries.join("\n");
}

const out = `// Generated by scripts/gen-icon-nodes.mjs from lucide-react. Do not edit by hand.
import type { IconNode } from "lucide-react";

export const REDESIGN_ICON_NODES: Record<string, IconNode> = {
${mapBlock("redesignIcons")}
};

export const PLATFORM_ICON_NODES: Record<string, IconNode> = {
${mapBlock("platformIcons")}
};
`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
process.stdout.write(`${Object.keys(nodes).length} icons -> ${path.relative(root, outFile)}\n`);
